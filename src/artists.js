// This file replaced a hand-written list of ~700 [title, artist] pairs. The
// reason is throughput: resolving a hand-written title costs one throttled
// /search per artist *and* can silently resolve to the wrong song, so every
// entry needed a matcher gate. Seeding by artist instead means one /search
// returns that artist's real catalog, and every track harvested from it is by
// definition a real song with a real preview. No matching, no unresolved rows.
//
//   node tools/build-packs.mjs            # build every genre
//   node tools/build-packs.mjs pop rap    # just these
//   node tools/build-packs.mjs --repack   # re-derive from cache, no network
//
// The second number on each row is a fame tier, and it is the only subjective
// judgement in the file:
//
//   1  household name — someone who does not follow the genre knows the hits
//   2  well known inside the genre
//   3  deeper cut
//
// Tier feeds difficulty. It is combined with each track's rank inside its
// artist's own catalog (iTunes returns an artist's songs roughly by
// popularity), and the pack is then split into equal easy/medium/hard bands.
// So tier does not need to be precise — it needs to be roughly ordered. Being
// one tier out moves a song a few places in a ranking, not into the wrong band.

