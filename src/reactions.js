/**
 * A shuffle bag: every message is dealt once, in random order, before any is
 * dealt again. So the same line never appears twice in a row, and none repeats
 * until the pool is exhausted. When it refills, the first card of the new deck
 * is never the last one dealt.
 *
 * `random` is injectable so tests can drive it; it defaults to Math.random.
 */
export function makeReactionPicker(messages = wrongGuessMessages, random = Math.random) {
  const pool = [...new Set(messages)].filter((m) => typeof m === 'string' && m.trim());
  let deck = [];
  let last = null;

  function refill() {
    deck = pool.slice();
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    // The next card is deck.pop(); keep it from matching the previous one.
    if (deck.length > 1 && deck[deck.length - 1] === last) {
      [deck[0], deck[deck.length - 1]] = [deck[deck.length - 1], deck[0]];
    }
  }

  return function next() {
    if (!pool.length) return '';
    if (!deck.length) refill();
    last = deck.pop();
    return last;
  };
}
